"""A catalog of 140 realistic MCP-style tools from 16 servers, with deliberate near-duplicates
(every tracker has search_issues, every chat or mail server can send a message, and so on).

Each tool is written the way an MCP server's tools/list would describe it; the client prefixes the
server name (github__search_issues), as mcp_lab.MCPTool does.
"""

S, I, B = "string", "integer", "boolean"


def p(type_, desc, *, opt=False, enum=None, items=None):
    d = {"type": type_, "description": desc}
    if enum:
        d["enum"] = enum
    if items:
        d["items"] = {"type": items}
    return d, opt


def T(_server, _name, _desc, /, **params):
    props = {k: v[0] for k, v in params.items()}
    req = [k for k, v in params.items() if not v[1]]
    return {"server": _server, "name": f"{_server}__{_name}", "description": _desc,
            "input_schema": {"type": "object", "properties": props, "required": req}}


